export type ServiceLogo =
  | { title: string; path: string; hex: string }
  | { title: string; Mark: () => JSX.Element };

const normalize = (s: string) =>
  s.toLowerCase().replace(/\.(com|net|org|io)\b/g, "").replace(/[^a-z0-9]/g, "");

const exact = new Map<string, ServiceLogo>();
function register(logo: ServiceLogo, names: string[]) {
  for (const name of names) {
    const key = normalize(name);
    if (key && !exact.has(key)) exact.set(key, logo);
  }
}
for (const [icon, ...aliases] of TABLE) {
  const logo = { title: icon.title, path: icon.path, hex: icon.hex };
  register(logo, [icon.title, icon.slug, ...aliases]);
}
for (const { title, aliases, Mark } of CUSTOM_MARKS) {
  register({ title, Mark }, [title, ...aliases]);
}
// Prefix matches ("Google Workspace" -> Google) only for names long enough
// not to collide, longest first so "protonmail" wins over "proton".
const prefixes = [...exact.keys()]
  .filter((k) => k.length >= 4)
  .sort((a, b) => b.length - a.length);

function lookup(name: string): ServiceLogo | undefined {
  const key = normalize(name);
  if (!key) return undefined;
  const hit = exact.get(key);
  if (hit) return hit;
  const prefix = prefixes.find((p) => key.startsWith(p));
  return prefix ? exact.get(prefix) : undefined;
}

export function findServiceLogo(
  issuer: string,
  account: string,
): ServiceLogo | undefined {
  // Fall back to the account's email domain ("me@gmail.com" -> Gmail).
  const domain = account.split("@")[1]?.split(".")[0] ?? "";
  return lookup(issuer) ?? (issuer.trim() ? undefined : lookup(domain));
}
